#nullable enable
namespace App
{
    /// <summary>
    /// 敵スキルの種別。StageConfig.EnemySkills に設定してステージごとのギミックを定義する。
    /// </summary>
    public enum EnemySkillType
    {
        // ─── ボード妨害 ───────────────────────────────────────────
        Shark,          // サメマスク  ：一定時間ごとにぷよを自動消去してHP回復
        FireTile,       // 炎マスク    ：指定マスを通過したぷよが消滅
        Pineapple,      // パイナップル：2回消さないと消えない特殊ぷよ
        Skull,          // どくろ      ：一定時間後にぷよの一部を別色に変色
        IcePuyo,        // 氷ぷよ      ：隣接消去で解凍、そのままでは消せない
        Magnet,         // 磁石マスク  ：落下ぷよが一定列に引き寄せられる
        Zombie,         // ゾンビ      ：消えたぷよが一定確率でおじゃまとして復活
        Multiply,       // 増殖        ：おじゃまぷよが消されると2個に分裂して復活

        // ─── 時間・操作干渉 ────────────────────────────────────────
        Clock,          // 時計マスク  ：定期的に制限時間を削る
        Mirror,         // 鏡マスク    ：一定時間、左右操作が反転

        // ─── 無効化 ──────────────────────────────────────────────
        NullifyDropkick,        // ドロップキック無効：保留消化を封じる
        NullifyAllSkills,       // 全スキル無効      ：プレイヤーの全スキルを使用不可
        NullifySkillByColor,    // 単色スキル無効    ：特定色のスキル1種を封じる
        SealHold,               // 保留封印          ：新しい保留が出現しなくなる
        ChainCap,               // チェーン上限      ：N連以上の追加ダメージが0
    }
}
#nullable disable
